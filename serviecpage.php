  document.addEventListener("DOMContentLoaded", function () {

  const carousel = document.querySelector(".services-hero-carousel");

  if (!carousel) return;

  const track = carousel.querySelector(".services-carousel-track");
  const slides = carousel.querySelectorAll(".services-carousel-track > div");
  const dots = carousel.querySelectorAll(".services-carousel-dot");

  let currentSlide = 0;
  let autoSlide;

  function showSlide(index) {

    currentSlide = index;

    track.style.transform = `translateX(-${currentSlide * 100}%)`;

    dots.forEach((dot, i) => {
      if (i === currentSlide) {
        dot.classList.remove("bg-[#ff7a00]/50");
        dot.classList.add("bg-[#ff7a00]");
      } else {
        dot.classList.remove("bg-[#ff7a00]");
        dot.classList.add("bg-[#ff7a00]/50");
      }
    });

  }

  function nextSlide() {
    currentSlide = (currentSlide + 1) % slides.length;
    showSlide(currentSlide);
  }

  function startAutoSlide() {
    autoSlide = setInterval(nextSlide, 3000);
  }

  function stopAutoSlide() {
    clearInterval(autoSlide);
  }


  /* DOT CLICK */
  dots.forEach((dot, index) => {

    dot.addEventListener("click", function () {
      stopAutoSlide();
      showSlide(index);
      startAutoSlide();
    });

  });


  /* PAUSE ON HOVER */
  carousel.addEventListener("mouseenter", stopAutoSlide);
  carousel.addEventListener("mouseleave", startAutoSlide);


  /* START */
  showSlide(0);
  startAutoSlide();

});
